1. HOW DO YOU ENSURE DATA QUALITY
  
"I ensure data quality by implementing validation checks at every stage of the ETL pipeline. During ingestion, I check for missing, duplicate, or invalid records. During transformation, I apply business rules, standardize data formats, and verify calculations. Before loading the data, I perform reconciliation checks by comparing record counts and key metrics against the source. I also automate monitoring and logging so any data issues are detected and addressed quickly. This ensures the data used for reporting and analytics is accurate, complete, and reliable."


  2. WHAT IS YOUR TYPICAL DAY AS A SENIOR AUTOMATION AND ANALYTICS ENGINEER
  
  " As a Senior Automation and Analytics Engineer, I start my day by reviewing the status of ongoing projects, checking automated workflows, data pipelines, and any issues that may affect our solutions. I make sure that PBI reporting, automated workflows, data pipelines are working as expected and address any issues that may have.

  A significant part of my day involves engagement with stakeholder to understand reporting and business improvement requirements. I gather these requirements, translate them into technical solutions and design a scalable reporting solutions. I also build and maintain data pipelines and reporting using SQL and MS Powerplatform technologies to deliver executive dashboards that drives data-driven decisions.

  As a senior engineer, I also revisit design solutions, documents processes, conducts product demos and mentoring new developers/engineers on some technical guidelines and best practices so that we can deliver a high quality solutions to our stakeholders.


  3. WHAT IS A GOOD CODE REVIEW?

  "A good code review checks that the code is correct, easy to understand, follows coding standards, and meets the business requirements. It should also look for potential issues with performance, security, and data quality. Most importantly, it should be a collaborative process where reviewers provide constructive feedback to improve the solution."
  
  4. WHAT DO YOU DO WHEN YOU DISAGREE WITH OTHER ENGINEERS?

  "When I disagree with another engineer, I focus on understanding their perspective and the problem we're trying to solve. I discuss the pros and cons of each approach using facts and data rather than opinions. If needed, we can do a quick proof of concept to compare options. Once a decision is made, I support it and work with the team to move forward."
  
  5. HOW DO YOU HANDLE TECHNICAL DEBTS
  "In Power BI and data engineering projects, technical debt can be things like hardcoded values, complex queries, duplicated logic, or manual processes. I document these items and gradually refactor them into more scalable and reusable solutions while delivering business requirements."
  
  6. HOW DO YOU RELEASE A FEATURE IN PRODUCTION?
  "Before releasing a feature to production, I ensure it has been properly developed, tested, and reviewed. I deploy it first to lower environments such as DEV and UAT, complete user acceptance testing, and obtain the necessary approvals. Once approved, I follow the deployment process, monitor the solution after release, and quickly address any issues that arise."
  
  7. HOW DO YOU HANDLE INCIDENTS IN PRODUCTION?
  "I focus on stabilizing the system first, investigate the root cause, implement a fix or rollback if necessary, and then document lessons learned to prevent the issue from happening again."

  8. HOW DO YOU MANAGE COMPETING PRIORITIES?
  "I prioritize requests based on business impact, urgency, and deadlines. I work with stakeholders to understand priorities and focus on the tasks that deliver the most value to the business."

  9. HOW DO YOU WORK WITH NON-TECHNICAL STAKEHOLDER
  "I work with non-technical stakeholders by communicating in simple, business-friendly language and focusing on the outcomes rather than technical details. I make sure I understand their requirements, provide regular updates, and use visuals or demonstrations when needed to ensure we're aligned."
  
  10. WHAT WOULD YOU DO IF A STAKEHOLDER ASKS YOU TO BYPASS THE NORMAL PROCESS?
  "I would respectfully explain the risks of bypassing the process and work with the stakeholder to find an approved solution. Following established processes helps ensure quality, security, and compliance."

  11. HOW DO YOU DOCUMENT YOUR WORK?
